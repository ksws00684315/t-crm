#!/usr/bin/env bash
# Local preview of the working tree that contains this script. Not for servers.
#   deploy/scripts/preview.sh up|down|reset
# up builds both front ends into deploy/www-preview, then starts the compose project tcrm-preview.
# See deploy/README.md.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

ENV_FILE="$ROOT/deploy/.env.preview"
COMPOSE_FILE="deploy/docker-compose.preview.yml"
PROJECT="tcrm-preview"

usage() {
  echo "用法：deploy/scripts/preview.sh up|down|reset" >&2
  exit 1
}

require_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    echo "缺少命令：docker。请先安装后再执行。" >&2
    exit 1
  fi
  if ! docker compose version >/dev/null 2>&1; then
    echo "缺少 Docker Compose 插件（docker compose）。请先安装后再执行。" >&2
    exit 1
  fi
  if ! docker info >/dev/null 2>&1; then
    echo "Docker 没有在运行。请先启动 Docker 后再执行。" >&2
    exit 1
  fi
}

require_up_tools() {
  local cmd
  require_docker
  for cmd in pnpm node openssl; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
      echo "缺少命令：${cmd}。请先安装后再执行。" >&2
      exit 1
    fi
  done
}

# The compose project name is fixed, so this volume is shared by every checkout.
# PostgreSQL only initializes credentials when the volume is empty.
preview_volume_exists() {
  docker volume inspect "${PROJECT}_pgdata" >/dev/null 2>&1
}

compose() {
  if [[ -f "$ENV_FILE" ]]; then
    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" --env-file "$ENV_FILE" "$@"
  else
    docker compose -p "$PROJECT" -f "$COMPOSE_FILE" "$@"
  fi
}

generate_env() {
  local db_user db_pass redis_pass admin_user admin_pass secret salt tmp bytes
  db_user="pv$(openssl rand -hex 4)" || exit 1
  db_pass="$(openssl rand -hex 16)" || exit 1
  redis_pass="$(openssl rand -hex 16)" || exit 1
  admin_user="pa$(openssl rand -hex 4)" || exit 1
  admin_pass="$(openssl rand -hex 16)" || exit 1
  secret="$(openssl rand -base64 32 | tr -d '\n')" || exit 1
  salt="$(openssl rand -hex 32 | tr -d '\n')" || exit 1
  if [[ ! "$admin_user" =~ ^[A-Za-z0-9_.-]{3,64}$ ]]; then
    echo "生成的平台管理员用户名不符合规则，请重试。" >&2
    exit 1
  fi
  if [[ ! "$admin_pass" =~ ^[[:print:]]{10,72}$ ]]; then
    echo "生成的平台管理员密码不符合规则，请重试。" >&2
    exit 1
  fi
  bytes="$(printf '%s' "$secret" | openssl base64 -d -A | wc -c | tr -d '[:space:]')" || exit 1
  if [[ "$bytes" -ne 32 ]]; then
    echo "生成的 TCRM_SECRET_KEY 不是 32 字节，请重试。" >&2
    exit 1
  fi
  if [[ "${#salt}" -lt 32 ]]; then
    echo "生成的 TCRM_IP_HASH_SALT 短于 32 字符，请重试。" >&2
    exit 1
  fi
  tmp="$(mktemp)"
  chmod 600 "$tmp"
  {
    printf '%s\n' '# Generated by deploy/scripts/preview.sh for local preview. Do not commit.'
    printf 'TCRM_DB_NAME=%s\n' 'tcrm'
    printf 'TCRM_DB_USERNAME=%s\n' "$db_user"
    printf 'TCRM_DB_PASSWORD=%s\n' "$db_pass"
    printf 'TCRM_REDIS_PASSWORD=%s\n' "$redis_pass"
    printf 'TCRM_BOOTSTRAP_ADMIN_USERNAME=%s\n' "$admin_user"
    printf 'TCRM_BOOTSTRAP_ADMIN_PASSWORD=%s\n' "$admin_pass"
    printf 'TCRM_CORS_ALLOWED_ORIGINS=\n'
    printf 'TCRM_LINK_BASE_URL=%s\n' 'https://t.preview.invalid'
    printf 'TCRM_KOL_PORTAL_BASE_URL=%s\n' 'https://kol.preview.invalid'
    printf 'TCRM_ADMIN_BASE_URL=%s\n' 'https://admin.preview.invalid'
    printf 'TCRM_SECRET_KEY="%s"\n' "$secret"
    printf 'TCRM_MAIL_API_KEY=\n'
    printf 'TCRM_MAIL_FROM=\n'
    printf 'TCRM_REDIRECT_FALLBACK_URL=%s\n' 'https://fallback.preview.invalid'
    printf 'TCRM_IP_HASH_SALT=%s\n' "$salt"
  } >"$tmp"
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  GENERATED_USER="$admin_user"
  GENERATED_PASS="$admin_pass"
  generated=1
}

print_creds_once() {
  if [[ "${generated:-0}" -eq 1 && "${creds_printed:-0}" -eq 0 ]]; then
    creds_printed=1
    echo "平台管理员（仅此次打印，之后可在 deploy/.env.preview 中查看）："
    echo "  用户名：${GENERATED_USER}"
    echo "  密码：${GENERATED_PASS}"
  fi
}

wait_healthy() {
  local service="$1"
  local deadline status id
  deadline=$((SECONDS + 300))
  echo "等待 ${service} 健康检查通过…"
  while [[ "$SECONDS" -lt "$deadline" ]]; do
    id="$(compose ps -q "$service" 2>/dev/null || true)"
    if [[ -n "$id" ]]; then
      status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$id" 2>/dev/null || true)"
      if [[ "$status" == "healthy" ]]; then
        return 0
      fi
      if [[ "$status" == "unhealthy" ]]; then
        break
      fi
    fi
    sleep 3
  done
  echo "健康检查未通过（服务 ${service}）。" >&2
  echo "查看日志：docker compose -p ${PROJECT} -f ${COMPOSE_FILE} logs ${service}" >&2
  compose ps || true
  exit 1
}

cmd_up() {
  require_docker
  generated=0
  creds_printed=0
  trap print_creds_once EXIT
  if [[ ! -f "$ENV_FILE" ]] && preview_volume_exists; then
    echo "已有预览数据（可能来自其他目录）。请从原目录复制 deploy/.env.preview 到这里，或执行 preview.sh reset 清空后重建。" >&2
    exit 1
  fi
  require_up_tools
  if [[ ! -f "$ENV_FILE" ]]; then
    generate_env
  fi
  # Absolute path so the build works no matter which directory invoked this script.
  export TCRM_STATIC_DIR="$ROOT/deploy/www-preview"
  "$ROOT/deploy/scripts/build-static.sh"
  docker compose -p "$PROJECT" -f "$COMPOSE_FILE" --env-file "$ENV_FILE" up -d --build
  wait_healthy crm-admin
  wait_healthy crm-redirect
  compose ps
  print_creds_once
  echo "管理端    http://localhost:8890"
  echo "达人端    http://localhost:8891"
  echo "跳转服务  http://localhost:8892  （/t/…、/i/…、/healthz）"
}

cmd_down() {
  require_docker
  compose down
}

cmd_reset() {
  local reply
  require_docker
  printf '将删除预览环境的数据卷和 deploy/.env.preview。输入 yes 确认：'
  read -r reply
  if [[ "$reply" != "yes" ]]; then
    echo "已取消。" >&2
    exit 1
  fi
  compose down -v
  rm -f "$ENV_FILE"
  echo "预览环境已清空。"
}

case "${1:-}" in
  up) cmd_up ;;
  down) cmd_down ;;
  reset) cmd_reset ;;
  *) usage ;;
esac
