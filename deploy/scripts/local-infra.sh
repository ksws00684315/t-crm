#!/usr/bin/env bash
# Shared local PostgreSQL and Redis used by preview, native development and task worktrees.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

ENV_FILE="${TCRM_LOCAL_ENV_FILE:-$ROOT/deploy/.env.local}"
COMPOSE_FILE="$ROOT/deploy/docker-compose.dev.yml"
PREVIEW_FILE="$ROOT/deploy/docker-compose.preview.yml"
BACKUP_DIR="${TCRM_LOCAL_BACKUP_DIR:-$ROOT/deploy/local-backups}"
PROJECT_OVERRIDE="${TCRM_LOCAL_INFRA_PROJECT:-}"
NETWORK_OVERRIDE="${TCRM_LOCAL_INFRA_NETWORK:-}"
DB_PORT_OVERRIDE="${TCRM_LOCAL_INFRA_DB_PORT:-}"
REDIS_PORT_OVERRIDE="${TCRM_LOCAL_INFRA_REDIS_PORT:-}"

usage() {
  echo "用法：deploy/scripts/local-infra.sh up|down|status|backup|restore <文件>|psql|migrate-from-preview" >&2
  exit 1
}

require_docker() {
  command -v docker >/dev/null 2>&1 || { echo "缺少命令：docker。" >&2; exit 1; }
  docker compose version >/dev/null 2>&1 || { echo "缺少 Docker Compose 插件。" >&2; exit 1; }
  docker info >/dev/null 2>&1 || { echo "Docker 没有在运行。" >&2; exit 1; }
}

generate_env() {
  local db_user db_pass redis_pass admin_user admin_pass secret salt tmp
  db_user="tc$(openssl rand -hex 5)"
  db_pass="$(openssl rand -hex 24)"
  redis_pass="$(openssl rand -hex 24)"
  admin_user="ta$(openssl rand -hex 5)"
  admin_pass="$(openssl rand -hex 18)"
  secret="$(openssl rand -base64 32 | tr -d '\n')"
  salt="$(openssl rand -hex 32)"
  mkdir -p "$(dirname "$ENV_FILE")"
  tmp="$(mktemp "$(dirname "$ENV_FILE")/.env.local.XXXXXX")"
  chmod 600 "$tmp"
  {
    echo '# Generated by deploy/scripts/local-infra.sh. Do not commit.'
    printf 'TCRM_LOCAL_INFRA_PROJECT=%s\n' "${PROJECT_OVERRIDE:-tcrm-local}"
    printf 'TCRM_LOCAL_INFRA_NETWORK=%s\n' "${NETWORK_OVERRIDE:-tcrm-local}"
    printf 'TCRM_DB_PORT=%s\n' "${DB_PORT_OVERRIDE:-55432}"
    printf 'TCRM_REDIS_PORT=%s\n' "${REDIS_PORT_OVERRIDE:-46391}"
    printf 'TCRM_DB_HOST=localhost\nTCRM_DB_NAME=tcrm\n'
    printf 'TCRM_DB_USERNAME=%s\nTCRM_DB_PASSWORD=%s\n' "$db_user" "$db_pass"
    printf 'TCRM_REDIS_HOST=localhost\nTCRM_REDIS_PASSWORD=%s\n' "$redis_pass"
    printf 'TCRM_BOOTSTRAP_ADMIN_USERNAME=%s\nTCRM_BOOTSTRAP_ADMIN_PASSWORD=%s\n' "$admin_user" "$admin_pass"
    printf 'TCRM_CORS_ALLOWED_ORIGINS=\n'
    printf 'TCRM_LINK_BASE_URL=https://t.local.invalid\n'
    printf 'TCRM_KOL_PORTAL_BASE_URL=https://kol.local.invalid\n'
    printf 'TCRM_ADMIN_BASE_URL=https://admin.local.invalid\n'
    printf 'TCRM_SECRET_KEY="%s"\n' "$secret"
    printf 'TCRM_MAIL_API_KEY=\nTCRM_MAIL_FROM=\n'
    printf 'TCRM_REDIRECT_FALLBACK_URL=https://fallback.local.invalid\n'
    printf 'TCRM_IP_HASH_SALT=%s\n' "$salt"
    printf 'SPRING_FLYWAY_OUT_OF_ORDER=true\n'
    printf 'SPRING_FLYWAY_IGNORE_MIGRATION_PATTERNS=*:missing\n'
  } >"$tmp"
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "已生成 ${ENV_FILE}（权限 600）。管理员账号：${admin_user}；密码仅写入该文件。"
}

compose() {
  local args=(-p "${PROJECT_OVERRIDE:-tcrm-local}" -f "$COMPOSE_FILE" --env-file "$ENV_FILE")
  [[ -n "$PROJECT_OVERRIDE" ]] && export TCRM_LOCAL_INFRA_PROJECT="$PROJECT_OVERRIDE"
  [[ -n "$NETWORK_OVERRIDE" ]] && export TCRM_LOCAL_INFRA_NETWORK="$NETWORK_OVERRIDE"
  [[ -n "$DB_PORT_OVERRIDE" ]] && export TCRM_LOCAL_INFRA_DB_PORT="$DB_PORT_OVERRIDE"
  [[ -n "$REDIS_PORT_OVERRIDE" ]] && export TCRM_LOCAL_INFRA_REDIS_PORT="$REDIS_PORT_OVERRIDE"
  docker compose "${args[@]}" "$@"
}

require_env() {
  if [[ ! -f "$ENV_FILE" ]]; then
    echo "找不到 ${ENV_FILE}，请先运行 local-infra.sh up。" >&2
    exit 1
  fi
  chmod 600 "$ENV_FILE"
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
  PROJECT_OVERRIDE="${PROJECT_OVERRIDE:-${TCRM_LOCAL_INFRA_PROJECT:-tcrm-local}}"
  NETWORK_OVERRIDE="${NETWORK_OVERRIDE:-${TCRM_LOCAL_INFRA_NETWORK:-tcrm-local}}"
  DB_PORT_OVERRIDE="${DB_PORT_OVERRIDE:-${TCRM_LOCAL_INFRA_DB_PORT:-}}"
  REDIS_PORT_OVERRIDE="${REDIS_PORT_OVERRIDE:-${TCRM_LOCAL_INFRA_REDIS_PORT:-}}"
}

wait_healthy() {
  local service id status deadline
  for service in postgres redis; do
    deadline=$((SECONDS + 180))
    status=""
    echo "等待 $service 健康检查…"
    while (( SECONDS < deadline )); do
      id="$(compose ps -q "$service" 2>/dev/null || true)"
      if [[ -n "$id" ]]; then
        status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$id" 2>/dev/null || true)"
        [[ "$status" == healthy ]] && break
        [[ "$status" == unhealthy ]] && break
      fi
      sleep 2
    done
    if [[ "${status:-}" != healthy ]]; then
      echo "$service 健康检查未通过。查看日志：deploy/scripts/local-infra.sh status" >&2
      compose logs --tail=100 "$service" >&2 || true
      exit 1
    fi
  done
}

cmd_up() {
  require_docker
  command -v openssl >/dev/null 2>&1 || { echo "缺少 openssl。" >&2; exit 1; }
  [[ -f "$ENV_FILE" ]] || generate_env
  require_env
  [[ -n "${TCRM_DB_USERNAME:-}" && -n "${TCRM_DB_PASSWORD:-}" && -n "${TCRM_REDIS_PASSWORD:-}" ]] || {
    echo "本地环境文件缺少数据库或 Redis 密码。" >&2; exit 1;
  }
  compose up -d
  wait_healthy
  compose ps
}

cmd_status() {
  require_docker
  require_env
  compose ps
}

cmd_down() {
  require_docker
  require_env
  compose down
}

cmd_backup() {
  require_docker
  require_env
  mkdir -p "$BACKUP_DIR"
  chmod 700 "$BACKUP_DIR"
  local stamp pgfile redisfile
  stamp="$(date '+%Y%m%d-%H%M%S')"
  pgfile="$BACKUP_DIR/${PROJECT_OVERRIDE:-tcrm-local}-$stamp.sql.gz"
  redisfile="$BACKUP_DIR/${PROJECT_OVERRIDE:-tcrm-local}-$stamp.rdb"
  compose exec -T postgres pg_dump --no-owner -U "$TCRM_DB_USERNAME" -d "$TCRM_DB_NAME" | gzip >"$pgfile"
  compose exec -T redis sh -c 'REDISCLI_AUTH="$TCRM_REDIS_PASSWORD" redis-cli SAVE >/dev/null && cat /data/dump.rdb' >"$redisfile"
  chmod 600 "$pgfile" "$redisfile"
  echo "数据库备份：$pgfile"
  echo "Redis RDB：$redisfile"
}

cmd_restore() {
  local file="${1:-}" reply rdb_file redis_volume backup_name
  [[ -n "$file" && -f "$file" ]] || { echo "用法：deploy/scripts/local-infra.sh restore <SQL或SQL.GZ文件>" >&2; exit 1; }
  require_docker
  require_env
  printf '恢复将覆盖共享数据库中的对象。输入 yes 确认：'
  read -r reply
  [[ "$reply" == yes ]] || { echo "已取消。"; return 0; }
  compose exec -T postgres psql -v ON_ERROR_STOP=1 -U "$TCRM_DB_USERNAME" -d "$TCRM_DB_NAME" \
    -c 'DROP SCHEMA public CASCADE; CREATE SCHEMA public;'
  if [[ "$file" == *.gz ]]; then
    gzip -dc "$file" | compose exec -T postgres psql -v ON_ERROR_STOP=1 -U "$TCRM_DB_USERNAME" -d "$TCRM_DB_NAME"
  else
    compose exec -T postgres psql -v ON_ERROR_STOP=1 -U "$TCRM_DB_USERNAME" -d "$TCRM_DB_NAME" <"$file"
  fi
  if [[ "$file" == *.sql.gz ]]; then
    backup_name="${file%.sql.gz}"
  else
    backup_name="${file%.sql}"
  fi
  rdb_file="${backup_name}.rdb"
  if [[ -f "$rdb_file" ]]; then
    redis_volume="${PROJECT_OVERRIDE:-tcrm-local}_redisdata"
    compose stop redis
    if ! docker run --rm -v "$redis_volume:/data" -v "$(cd "$(dirname "$rdb_file")" && pwd):/backup:ro" redis:7.4.5 \
      sh -c 'set -eu
        rm -rf /data/appendonlydir /data/appendonly.aof*
        cp "/backup/$1" /data/dump.rdb
        chown 999:999 /data/dump.rdb
        redis-server --dir /data --dbfilename dump.rdb --appendonly no --daemonize no --bind 127.0.0.1 --port 6379 >/tmp/redis-restore.log 2>&1 &
        server_pid=$!
        ready=0
        i=0
        while [ "$i" -lt 60 ]; do
          if redis-cli -p 6379 ping >/dev/null 2>&1; then
            ready=1
            break
          fi
          i=$((i + 1))
          sleep 0.5
        done
        if [ "$ready" -ne 1 ]; then
          cat /tmp/redis-restore.log >&2
          kill "$server_pid" 2>/dev/null || true
          exit 1
        fi
        redis-cli -p 6379 config set appendonly yes >/dev/null
        ready=0
        i=0
        while [ "$i" -lt 120 ]; do
          state="$(redis-cli -p 6379 info persistence | tr -d "\r")"
          if printf "%s\n" "$state" | grep -q "^aof_rewrite_in_progress:0$" && [ -f /data/appendonlydir/appendonly.aof.manifest ]; then
            ready=1
            break
          fi
          i=$((i + 1))
          sleep 0.5
        done
        if [ "$ready" -ne 1 ]; then
          cat /tmp/redis-restore.log >&2
          kill "$server_pid" 2>/dev/null || true
          echo "Redis AOF 重建超时。" >&2
          exit 1
        fi
        redis-cli -p 6379 shutdown >/dev/null 2>&1 || true
        wait "$server_pid" || true' sh "$(basename "$rdb_file")"; then
      compose start redis || true
      echo "Redis RDB/AOF 恢复失败；已尝试重新启动共享 Redis。备份文件仍保留，可排查后重试。" >&2
      exit 1
    fi
    compose start redis
    wait_healthy
    echo "PostgreSQL 与配套 Redis RDB 均已恢复。"
  else
    echo "PostgreSQL 已恢复；配套 RDB 未找到（${rdb_file}），Redis 数据未更改。"
  fi
}

cmd_psql() {
  require_docker
  require_env
  compose exec postgres psql -U "$TCRM_DB_USERNAME" -d "$TCRM_DB_NAME"
}

cmd_migrate_from_preview() {
  require_docker
  local preview_env="${TCRM_OLD_PREVIEW_ENV_FILE:-$ROOT/deploy/.env.preview}"
  local preview_project="${TCRM_OLD_PREVIEW_PROJECT:-tcrm-preview}"
  [[ -f "$preview_env" ]] || { echo "找不到旧预览环境文件 ${preview_env}。" >&2; exit 1; }
  [[ ! -f "$ENV_FILE" ]] || require_env
  if [[ "$preview_project" == tcrm-preview && "${TCRM_ALLOW_OWNER_PREVIEW_MIGRATION:-}" != yes ]]; then
    echo "拒绝操作负责人默认项目 tcrm-preview。自测请指定 TCRM_OLD_PREVIEW_PROJECT=tcrm-p35。" >&2
    exit 1
  fi
  if [[ "$preview_project" == "${PROJECT_OVERRIDE:-tcrm-local}" ]]; then
    echo "旧预览项目与共享中间件项目不能相同，避免源卷和目标卷指向同一对象。" >&2
    exit 1
  fi
  mkdir -p "$BACKUP_DIR"
  chmod 700 "$BACKUP_DIR"
  # Back up any existing shared volume before replacing it with preview data.
  if docker volume inspect "${PROJECT_OVERRIDE:-tcrm-local}_pgdata" >/dev/null 2>&1 || \
    docker volume inspect "${PROJECT_OVERRIDE:-tcrm-local}_redisdata" >/dev/null 2>&1; then
    if [[ ! -f "$ENV_FILE" ]]; then
      echo "共享中间件数据卷已存在，但 $ENV_FILE 缺失；先恢复其凭证文件并完成备份，再迁移。" >&2
      exit 1
    fi
    require_env
    compose up -d
    wait_healthy
    cmd_backup
    compose down
  fi

  # Load the trusted local preview env file so pg_dump and redis-cli use its existing credentials.
  set -a
  # shellcheck disable=SC1090
  source "$preview_env"
  set +a
  local old_user old_db old_pass old_redis before_counts after_counts
  old_user="$TCRM_DB_USERNAME"
  old_db="${TCRM_DB_NAME:-tcrm}"
  old_pass="$TCRM_DB_PASSWORD"
  old_redis="$TCRM_REDIS_PASSWORD"
  local stamp src_pg src_redis dst_pg dst_redis
  stamp="$(date '+%Y%m%d-%H%M%S')"
  src_pg="${preview_project}_pgdata"
  src_redis="${preview_project}_redisdata"
  dst_pg="${PROJECT_OVERRIDE:-tcrm-local}_pgdata"
  dst_redis="${PROJECT_OVERRIDE:-tcrm-local}_redisdata"
  docker volume inspect "$src_pg" >/dev/null
  docker volume inspect "$src_redis" >/dev/null
  local preview_container redis_container
  preview_container="$(docker ps -q --filter "label=com.docker.compose.project=$preview_project" --filter 'label=com.docker.compose.service=postgres' | head -n1)"
  redis_container="$(docker ps -q --filter "label=com.docker.compose.project=$preview_project" --filter 'label=com.docker.compose.service=redis' | head -n1)"
  [[ -n "$preview_container" && -n "$redis_container" ]] || { echo "旧预览 PostgreSQL 或 Redis 容器未运行，无法先备份数据。" >&2; exit 1; }
  before_counts="$(docker exec "$preview_container" psql -U "$old_user" -d "$old_db" -Atc "SELECT (SELECT count(*) FROM crm_kol), (SELECT count(*) FROM sys_user)")"
  docker exec "$preview_container" pg_dump --no-owner -U "$old_user" -d "$old_db" | gzip >"$BACKUP_DIR/${preview_project}-$stamp.sql.gz"
  docker exec -e REDISCLI_AUTH="$old_redis" "$redis_container" sh -c 'redis-cli SAVE >/dev/null && cat /data/dump.rdb' >"$BACKUP_DIR/${preview_project}-$stamp.rdb"
  chmod 600 "$BACKUP_DIR/${preview_project}-$stamp.sql.gz" "$BACKUP_DIR/${preview_project}-$stamp.rdb"

  # Carry forward the old application credentials and encryption material without reformatting values.
  mkdir -p "$(dirname "$ENV_FILE")"
  cp "$preview_env" "$ENV_FILE"
  cat >>"$ENV_FILE" <<EOF
TCRM_LOCAL_INFRA_PROJECT=${PROJECT_OVERRIDE:-tcrm-local}
TCRM_LOCAL_INFRA_NETWORK=${NETWORK_OVERRIDE:-tcrm-local}
TCRM_DB_PORT=${DB_PORT_OVERRIDE:-55432}
TCRM_REDIS_PORT=${REDIS_PORT_OVERRIDE:-46391}
SPRING_FLYWAY_OUT_OF_ORDER=true
SPRING_FLYWAY_IGNORE_MIGRATION_PATTERNS=*:missing
EOF
  chmod 600 "$ENV_FILE"

  local preview_ids
  preview_ids="$(docker ps -q --filter "label=com.docker.compose.project=$preview_project")"
  while IFS= read -r container_id; do
    [[ -z "$container_id" ]] || docker stop "$container_id" >/dev/null
  done <<<"$preview_ids"
  compose down
  docker run --rm -v "$src_pg:/source:ro" -v "$dst_pg:/target" postgres:17.11 bash -c 'rm -rf /target/* /target/.[!.]* /target/..?*; cp -a /source/. /target/'
  docker run --rm -v "$src_redis:/source:ro" -v "$dst_redis:/target" redis:7.4.5 sh -c 'rm -rf /target/* /target/.[!.]* /target/..?*; cp -a /source/. /target/'
  cmd_up
  after_counts="$(compose exec -T postgres psql -U "$TCRM_DB_USERNAME" -d "$TCRM_DB_NAME" -Atc "SELECT (SELECT count(*) FROM crm_kol), (SELECT count(*) FROM sys_user)")"
  [[ "$before_counts" == "$after_counts" ]] || { echo "迁移前后达人数/用户数不一致：$before_counts -> $after_counts" >&2; exit 1; }
  echo "迁移前后达人数、用户数一致：${after_counts}。"
  echo "保留的旧卷：${src_pg}、${src_redis}。确认切换后由负责人手动删除。"
}

case "${1:-}" in
  up) cmd_up ;;
  down) cmd_down ;;
  status) cmd_status ;;
  backup) cmd_backup ;;
  restore) cmd_restore "${2:-}" ;;
  psql) cmd_psql ;;
  migrate-from-preview) cmd_migrate_from_preview ;;
  *) usage ;;
esac
